/**
 * Build script — assembles the two paste-ready ChabadOne code blocks.
 *
 *   node build/build.js
 *
 * Outputs:
 *   dist/header-code.html  → Custom Header Code box (fonts + Swiper CSS + minified style.css)
 *   dist/footer-code.html  → Custom Footer Code box (Swiper JS + minified script.js)
 *
 * No dependencies beyond Node itself. Minification is conservative:
 * comments/whitespace stripping only, so the output is always valid.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');

const SWIPER_VERSION = '11';
const SWIPER_CSS = `https://cdn.jsdelivr.net/npm/swiper@${SWIPER_VERSION}/swiper-bundle.min.css`;
const SWIPER_JS = `https://cdn.jsdelivr.net/npm/swiper@${SWIPER_VERSION}/swiper-bundle.min.js`;
const GOOGLE_FONTS =
  'https://fonts.googleapis.com/css2?family=Marcellus&family=Figtree:wght@400;500;600;700&display=swap';

/* ---------------- CSS minifier ---------------- */
/* csso with restructure OFF: several of our overrides deliberately rely on
   source order between equal-specificity rules, and restructuring merges /
   reorders rules. Compression only (colors, zeros, whitespace) is safe. */
const csso = require('csso');
function minifyCssHard(css) {
  return csso.minify(css, { restructure: false, comments: false }).css;
}
function minifyCss(css) {
  return css
    // strip comments (none of ours contain url(*) tricks)
    .replace(/\/\*[\s\S]*?\*\//g, '')
    // collapse whitespace
    .replace(/\s+/g, ' ')
    // tighten around punctuation
    .replace(/\s*([{}:;,>~])\s*/g, '$1')
    // keep a space where the CSS needs it back: "and(" is invalid in media queries
    .replace(/and\(/g, 'and (')
    // drop final semicolons in blocks
    .replace(/;}/g, '}')
    .trim();
}

/* ---------------- JS minifier ----------------
   terser (real minification: mangling + compression) — required since the
   Custom Footer Code box refuses to save payloads much past ~50K chars.
   ecma 5 output so nothing modern sneaks into the old CMS environment.
   The legacy line-stripper below is kept as documentation/fallback. */
const { minify: terserMinify } = require('terser');
async function minifyJsTerser(js) {
  const res = await terserMinify(js, {
    ecma: 2020,
    compress: { passes: 4, drop_console: true, unsafe: true, unsafe_arrows: true, unsafe_methods: true, booleans_as_integers: true, pure_getters: true },
    mangle: true,
    format: { comments: false },
  });
  if (res.error) throw res.error;
  return res.code;
}

function minifyJs(js) {
  const lines = js.split('\n');
  const out = [];
  let inBlockComment = false;
  for (let line of lines) {
    if (inBlockComment) {
      const end = line.indexOf('*/');
      if (end === -1) continue;
      line = line.slice(end + 2);
      inBlockComment = false;
    }
    // strip whole-line block comments and detect multiline openers
    let scan = line;
    let cleaned = '';
    while (true) {
      const start = scan.indexOf('/*');
      if (start === -1) { cleaned += scan; break; }
      // don't touch /* inside a string or regex — our source never does that
      const end = scan.indexOf('*/', start + 2);
      cleaned += scan.slice(0, start);
      if (end === -1) { inBlockComment = true; break; }
      scan = scan.slice(end + 2);
    }
    // strip lines that are purely // comments (never trailing ones — could be a URL)
    if (/^\s*\/\//.test(cleaned)) continue;
    cleaned = cleaned.replace(/\s+$/g, '');
    if (cleaned.trim() === '') continue;
    // collapse leading indentation
    out.push(cleaned.replace(/^\s+/, ''));
  }
  return out.join('\n');
}

/* ---------------- assemble ---------------- */
async function build() {
  const css = fs.readFileSync(path.join(SRC, 'style.css'), 'utf8');
  const js = fs.readFileSync(path.join(SRC, 'script.js'), 'utf8');
  const registerJs = fs.readFileSync(path.join(SRC, 'register-autofill.js'), 'utf8');

  fs.mkdirSync(DIST, { recursive: true });

  const header = [
    '<!-- SB redesign HEADER block (keep the Google Ads gtag block above this; generated by build/build.js — edit src/style.css) -->',
    '<link rel="preconnect" href="https://fonts.googleapis.com">',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    `<link rel="stylesheet" href="${GOOGLE_FONTS}">`,
    `<link rel="stylesheet" href="${SWIPER_CSS}">`,
    // chabad.org's official event-form redesign (same assets the Venetian site
    // uses); recolored to our palette via the --*-form-* variables in style.css
    '<link rel="stylesheet" href="https://w2.chabad.org/images/Shluchim/minisites/themes/form-redesign/form-style.css?v=7/17/2026">',
    '<style id="sb-theme">',
    minifyCssHard(css),
    '</style>',
    '<script src="https://w2.chabad.org/images/Shluchim/minisites/themes/form-redesign/form-script.js?v=7/17/2026"></script>',
    // site config consumed by the footer block (lives here because the
    // footer code box refuses to save past ~63KB url-encoded)
    '<script id="sb-config">' + [
      'window.SB_SPONSOR_TIERS={"23338":{heading:"Sponsorship Opportunities",blurb:"Sponsors help cover the evening' + String.fromCharCode(39) + 's program.",tiers:[{label:"Presenting Sponsor",amount:5000},{label:"Diamond Sponsor",amount:2500},{label:"Gold Sponsor",amount:1800},{label:"Silver Sponsor",amount:500},{label:"Community Sponsor",amount:360},{label:"Friend of The Gathering",amount:180}]}};',
      'window.SB_PAGE_THEMES={"23338":{accent:"#4A6752",accentDark:"#39503F",band:"#35493B",soft:"#F6ECE6"},"23305":{accent:"#A96F68",accentDark:"#8A5751",band:"#6E7768",soft:"#EFE4E0"}};',
      'window.SB_MW_BENEFITS={Basic:["Your special days on the community calendar","5% off all events and programs","Reserved High Holiday seat"],Chai:["10% off all events and programs","Listed on Chai donor wall","20% off Lulav and Esrog set"],Silver:["Annual mezuzah checking","1 co-sponsored Kiddush per year","VIP High Holiday seating","50% off Lulav and Esrog set","Listed on Silver donor wall"],Gold:["Annual mezuzah and tefillin checking","1 co-sponsored Kiddush per year","Lulav and Esrog set provided","Listed on Gold donor wall"]};'
    ].join('') + '</script>',
    // registration autofill + card-type module (self-contained; parked in
    // the header because the footer box is at its url-encoded size limit)
    '<script id="sb-register-autofill">',
    await minifyJsTerser(registerJs),
    '</script>',
    ''
  ].join('\n');

  const footer = [
    '<!-- SB redesign FOOTER block (generated by build/build.js — edit src/script.js) -->',
    `<script src="${SWIPER_JS}"></script>`,
    '<script id="sb-theme-js">',
    await minifyJsTerser(js),
    '</script>',
    ''
  ].join('\n');

  const headerPath = path.join(DIST, 'header-code.html');
  const footerPath = path.join(DIST, 'footer-code.html');
  fs.writeFileSync(headerPath, header);
  fs.writeFileSync(footerPath, footer);

  /* ---- externally-hosted variant (ChabadOne support's recommendation:
     the code boxes are size-capped; host the assets on GitHub Pages and
     paste only <link>/<script> tags). Set CDN_BASE once the repo exists,
     then paste the -cdn box files instead; pushing to GitHub deploys. ---- */
  const CDN_BASE = process.env.SB_CDN_BASE || 'https://cdn.jsdelivr.net/gh/rabbikraz/chabad-web-design@redesign';
  const siteCss = minifyCssHard(css);
  const siteJs = (await minifyJsTerser(registerJs)) + '\n' + (await minifyJsTerser(js));
  fs.writeFileSync(path.join(DIST, 'site.css'), siteCss);
  fs.writeFileSync(path.join(DIST, 'site.js'), siteJs);
  if (CDN_BASE) {
    const sbConfig = header.match(/<script id="sb-config">[\s\S]*?<\/script>/)[0];
    fs.writeFileSync(path.join(DIST, 'header-code-cdn.html'), [
      '<!-- SB redesign HEADER (CDN variant; assets served by jsDelivr from GitHub; generated by build/build.js) -->',
      '<link rel="preconnect" href="https://fonts.googleapis.com">',
      '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
      `<link rel="stylesheet" href="${GOOGLE_FONTS}">`,
      `<link rel="stylesheet" href="${SWIPER_CSS}">`,
      '<link rel="stylesheet" href="https://w2.chabad.org/images/Shluchim/minisites/themes/form-redesign/form-style.css?v=7/17/2026">',
      // Version-pinned loading: jsDelivr edges regionally served stale files
      // under rotating cache keys and ignored purges (cost us a full day).
      // The box synchronously reads dist/version.txt from
      // raw.githubusercontent.com (5-min cache, CORS *), then loads the
      // assets pinned to that exact commit sha - immutable jsDelivr URLs
      // that are either correct or absent, never silently stale.
      "<script>(function(){var v=window.SB_ASSET_V;if(!v){v='redesign';try{var x=new XMLHttpRequest();x.open('GET','https://raw.githubusercontent.com/rabbikraz/chabad-web-design/redesign/dist/version.txt?b='+Math.floor(Date.now()/3e5),false);x.send();if(x.status===200&&/^[0-9a-f]{7,40}\\s*$/.test(x.responseText))v=x.responseText.trim();}catch(e){}window.SB_ASSET_V=v;}" +
        "document.write('<link rel=\"stylesheet\" href=\"https://cdn.jsdelivr.net/gh/rabbikraz/chabad-web-design@'+v+'/dist/site.css\">');})()</scr" + "ipt>",
      '<script src="https://w2.chabad.org/images/Shluchim/minisites/themes/form-redesign/form-script.js?v=7/17/2026"></script>',
      sbConfig,
      ''
    ].join('\n'));
    fs.writeFileSync(path.join(DIST, 'footer-code-cdn.html'), [
      '<!-- SB redesign FOOTER (CDN variant; generated by build/build.js) -->',
      `<script src="${SWIPER_JS}"></script>`,
      "<script>(function(){var v=window.SB_ASSET_V;if(!v){v='redesign';try{var x=new XMLHttpRequest();x.open('GET','https://raw.githubusercontent.com/rabbikraz/chabad-web-design/redesign/dist/version.txt?b='+Math.floor(Date.now()/3e5),false);x.send();if(x.status===200&&/^[0-9a-f]{7,40}\\s*$/.test(x.responseText))v=x.responseText.trim();}catch(e){}window.SB_ASSET_V=v;}" +
        "document.write('<script src=\"https://cdn.jsdelivr.net/gh/rabbikraz/chabad-web-design@'+v+'/dist/site.js\"><'+'/scr'+'ipt>');})()</scr" + "ipt>",
      ''
    ].join('\n'));
  }

  // GUARD: the ChabadOne admin decodes HTML entities inside the code boxes
  // when saving, silently corrupting the payload (a literal '&#39;' in the JS
  // became ''' on the live site and killed the whole script). Refuse to build
  // anything containing a literal entity outside of tag-level markup.
  for (const p of [headerPath, footerPath]) {
    const body = fs.readFileSync(p, 'utf8')
      // tag attributes (href="...&display=swap") are fine — check only
      // the inline <style>/<script> payloads the CMS re-encodes
      .split(/<\/(?:style|script)>/)
      .filter((chunk) => /<(?:style|script)[^>]*>/.test(chunk))
      .map((chunk) => chunk.replace(/^[\s\S]*?<(?:style|script)[^>]*>/, ''))
      .join('\n');
    const hit = body.match(/&(?:[a-zA-Z]{2,8}|#\d{1,6});/);
    if (hit) {
      throw new Error(
        `HTML entity "${hit[0]}" found inside a <style>/<script> payload of ` +
        `${path.basename(p)} — the CMS admin will decode it and corrupt the block.`
      );
    }
  }

  const report = (p) => {
    const chars = fs.readFileSync(p, 'utf8').length;
    console.log(
      `${path.basename(p).padEnd(18)} ${String(chars).padStart(7)} chars` +
      ` (${(chars / 1024).toFixed(1)} KB)`
    );
  };
  report(headerPath);
  report(footerPath);
}

build().catch((e) => { console.error(e); process.exit(1); });
